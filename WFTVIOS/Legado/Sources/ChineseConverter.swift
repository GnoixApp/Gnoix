    private init() {}
    
    func toTraditional(_ text: String) -> String {
        var result = text
        for (simp, trad) in simpToTrad {
            result = result.replacingOccurrences(of: simp, with: trad)
        }
        return result
    }
    
    func toSimplified(_ text: String) -> String {
        var result = text
        for (simp, trad) in simpToTrad {
            result = result.replacingOccurrences(of: trad, with: simp)
        }
        return result
    }
    
    func convert(_ text: String, toSimplified: Bool) -> String {
        if toSimplified {
            return self.toSimplified(text)
        } else {
            return toTraditional(text)
        }
    }
